-- =============================================================================
-- PASO 3 (OPCIONAL) — PROPUESTA AUTOMÁTICA DE ZONA PARA CLIENTES EXISTENTES
-- =============================================================================
-- Busca el nombre del municipio dentro de la dirección escrita del cliente y deja la
-- zona como PROPUESTA (CONFIRMADA = 'N'). Si una dirección menciona dos municipios se
-- toma el nombre más largo (p. ej. "Villa Nueva" antes que "Guatemala"). Un usuario
-- debe revisar y confirmar desde la ficha del cliente. No toca clientes que ya tengan
-- ubicación registrada.
-- =============================================================================

PROMPT Proponiendo zona a clientes existentes según su dirección...

INSERT INTO PROYECTOANALISIS.CXC_CLIENTE_UBICACION (ID_CLIENTE, ID_ZONA, CONFIRMADA)
SELECT ID_CLIENTE, ID_ZONA, 'N'
  FROM (
    SELECT c.ID_CLIENTE, z.ID_ZONA,
           ROW_NUMBER() OVER (PARTITION BY c.ID_CLIENTE ORDER BY LENGTH(z.MUNICIPIO) DESC, z.ID_ZONA) RN
      FROM PROYECTOANALISIS.CLIENTE c
      JOIN PROYECTOANALISIS.CXC_ZONAS_COBRO z
        ON z.ESTADO = 'A'
       AND z.ZONA IS NULL
       -- Sin distinguir mayúsculas ni acentos ("Amatitlan" = "Amatitlán").
       AND UPPER(CONVERT(c.DIRECCION, 'US7ASCII'))
           LIKE '%' || UPPER(CONVERT(z.MUNICIPIO, 'US7ASCII')) || '%'
     WHERE c.DIRECCION IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM PROYECTOANALISIS.CXC_CLIENTE_UBICACION u WHERE u.ID_CLIENTE = c.ID_CLIENTE)
  )
 WHERE RN = 1;

COMMIT;

