-- =============================================================================
-- MIGRACIÓN 015 — zonas de cobro: territorio de rutas y ubicación de clientes.
-- =============================================================================
-- Motivo: al asignar documentos a una ruta aparecen facturas de toda la empresa,
-- porque la ruta solo tiene un nombre libre ("Ruta Centro Villa Canales") y el
-- cliente solo una dirección escrita ("Zona 2, Amatitlán"). El sistema no puede
-- saber qué clientes pertenecen al territorio de la ruta.
--
-- Esta migración agrega:
--   1. CXC_ZONAS_COBRO        catálogo de territorios (departamento → municipio → zona)
--                             con su centro en el mapa, radio y sucursal que lo atiende.
--   2. CXC_CLIENTE_UBICACION  zona y punto en el mapa de cada cliente (se registra una vez).
--                             Tabla aparte para no alterar CLIENTE, que comparten otros módulos.
--   3. CXC_RUTAS.ID_ZONA      territorio de la ruta.
--
-- Con esto, al asignar documentos a una ruta se muestran solo los clientes de su zona
-- (o dentro del radio desde el centro de la zona), ordenados por prioridad de cobro.
--
-- 100% aditivo: CREATE TABLE / ALTER TABLE ADD / índices. Ningún DROP ni DELETE.
-- Se puede ejecutar más de una vez: cada paso revisa si ya existe.
-- =============================================================================

PROMPT Migración CxC 015 — zonas de cobro: iniciando...

DECLARE
  v_count PLS_INTEGER;

  PROCEDURE ejecutar_si(p_condicion BOOLEAN, p_sql VARCHAR2) IS
  BEGIN
    IF p_condicion THEN
      EXECUTE IMMEDIATE p_sql;
    END IF;
  END;

  FUNCTION existe_tabla(p_tabla VARCHAR2) RETURN BOOLEAN IS
    n PLS_INTEGER;
  BEGIN
    SELECT COUNT(*) INTO n FROM ALL_TABLES WHERE OWNER = 'PROYECTOANALISIS' AND TABLE_NAME = p_tabla;
    RETURN n > 0;
  END;

  FUNCTION existe_columna(p_tabla VARCHAR2, p_columna VARCHAR2) RETURN BOOLEAN IS
    n PLS_INTEGER;
  BEGIN
    SELECT COUNT(*) INTO n FROM ALL_TAB_COLUMNS
     WHERE OWNER = 'PROYECTOANALISIS' AND TABLE_NAME = p_tabla AND COLUMN_NAME = p_columna;
    RETURN n > 0;
  END;

  FUNCTION existe_constraint(p_nombre VARCHAR2) RETURN BOOLEAN IS
    n PLS_INTEGER;
  BEGIN
    SELECT COUNT(*) INTO n FROM ALL_CONSTRAINTS WHERE OWNER = 'PROYECTOANALISIS' AND CONSTRAINT_NAME = p_nombre;
    RETURN n > 0;
  END;

  FUNCTION existe_indice(p_nombre VARCHAR2) RETURN BOOLEAN IS
    n PLS_INTEGER;
  BEGIN
    SELECT COUNT(*) INTO n FROM ALL_INDEXES WHERE OWNER = 'PROYECTOANALISIS' AND INDEX_NAME = p_nombre;
    RETURN n > 0;
  END;
BEGIN
  -- ---------------------------------------------------------------------------
  -- 1. CXC_ZONAS_COBRO — territorios de cobro
  -- ---------------------------------------------------------------------------
  ejecutar_si(NOT existe_tabla('CXC_ZONAS_COBRO'), q'[
    CREATE TABLE PROYECTOANALISIS.CXC_ZONAS_COBRO (
      ID_ZONA        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 1 INCREMENT BY 1,
      -- Código corto para pantallas y reportes (p. ej. GUA-VCA, GUA-Z01).
      CODIGO         VARCHAR2(15)  NOT NULL,
      DEPARTAMENTO   VARCHAR2(60)  NOT NULL,
      MUNICIPIO      VARCHAR2(80)  NOT NULL,
      -- Opcional: zona, aldea o colonia dentro del municipio (p. ej. "Zona 1").
      -- NULL = todo el municipio.
      ZONA           VARCHAR2(80),
      -- Nombre que se muestra: "Villa Canales" o "Guatemala · Zona 1".
      NOMBRE         VARCHAR2(150) NOT NULL,
      -- Centro del territorio: desde aquí se mide la distancia de los clientes.
      LATITUD        NUMBER(10,7)  NOT NULL,
      LONGITUD       NUMBER(10,7)  NOT NULL,
      -- Distancia máxima (km, línea recta) para considerar a un cliente dentro de la zona
      -- cuando no tiene zona asignada pero sí punto en el mapa.
      RADIO_KM       NUMBER(5,2)   DEFAULT 5 NOT NULL,
      -- Sucursal que atiende la zona (opcional).
      ID_SUCURSAL    NUMBER,
      ESTADO         CHAR(1)       DEFAULT 'A' NOT NULL,
      CONSTRAINT PK_CXC_ZONAS_COBRO PRIMARY KEY (ID_ZONA),
      CONSTRAINT UQ_CXC_ZONA_CODIGO UNIQUE (CODIGO),
      CONSTRAINT FK_CXC_ZONA_SUCURSAL FOREIGN KEY (ID_SUCURSAL)
        REFERENCES PROYECTOANALISIS.CXC_SUCURSALES (ID_SUCURSAL),
      CONSTRAINT CK_CXC_ZONA_ESTADO CHECK (ESTADO IN ('A', 'I')),
      CONSTRAINT CK_CXC_ZONA_LATITUD CHECK (LATITUD BETWEEN -90 AND 90),
      CONSTRAINT CK_CXC_ZONA_LONGITUD CHECK (LONGITUD BETWEEN -180 AND 180),
      CONSTRAINT CK_CXC_ZONA_RADIO CHECK (RADIO_KM BETWEEN 1 AND 50),
      CONSTRAINT CK_CXC_ZONA_CODIGO CHECK (REGEXP_LIKE(CODIGO, '^[A-Z0-9-]{2,15}$'))
    ) TABLESPACE USERS]');

  -- Un mismo territorio no se registra dos veces (sin distinguir mayúsculas/acentos de captura).
  ejecutar_si(NOT existe_indice('UX_CXC_ZONA_TERRITORIO'), q'[
    CREATE UNIQUE INDEX PROYECTOANALISIS.UX_CXC_ZONA_TERRITORIO
      ON PROYECTOANALISIS.CXC_ZONAS_COBRO (UPPER(DEPARTAMENTO), UPPER(MUNICIPIO), UPPER(NVL(ZONA, '-')))
      TABLESPACE USERS]');

  ejecutar_si(NOT existe_indice('IX_CXC_ZONA_SUCURSAL'), q'[
    CREATE INDEX PROYECTOANALISIS.IX_CXC_ZONA_SUCURSAL
      ON PROYECTOANALISIS.CXC_ZONAS_COBRO (ID_SUCURSAL) TABLESPACE USERS]');

  -- ---------------------------------------------------------------------------
  -- 2. CXC_CLIENTE_UBICACION — zona y punto en el mapa de cada cliente
  -- ---------------------------------------------------------------------------
  ejecutar_si(NOT existe_tabla('CXC_CLIENTE_UBICACION'), q'[
    CREATE TABLE PROYECTOANALISIS.CXC_CLIENTE_UBICACION (
      ID_CLIENTE            NUMBER       NOT NULL,
      ID_ZONA               NUMBER,
      LATITUD               NUMBER(10,7),
      LONGITUD              NUMBER(10,7),
      -- 'N' = propuesta automática (a partir de la dirección); 'S' = confirmada por un usuario.
      CONFIRMADA            CHAR(1)      DEFAULT 'N' NOT NULL,
      ID_USUARIO_ACTUALIZA  NUMBER,
      FECHA_ACTUALIZACION   DATE         DEFAULT SYSDATE NOT NULL,
      CONSTRAINT PK_CXC_CLIENTE_UBICACION PRIMARY KEY (ID_CLIENTE),
      CONSTRAINT FK_CXC_CU_CLIENTE FOREIGN KEY (ID_CLIENTE)
        REFERENCES PROYECTOANALISIS.CLIENTE (ID_CLIENTE),
      CONSTRAINT FK_CXC_CU_ZONA FOREIGN KEY (ID_ZONA)
        REFERENCES PROYECTOANALISIS.CXC_ZONAS_COBRO (ID_ZONA),
      CONSTRAINT FK_CXC_CU_USUARIO FOREIGN KEY (ID_USUARIO_ACTUALIZA)
        REFERENCES PROYECTOANALISIS.SEG_USUARIOS (ID_USUARIO),
      CONSTRAINT CK_CXC_CU_CONFIRMADA CHECK (CONFIRMADA IN ('S', 'N')),
      -- Latitud y longitud van juntas: las dos o ninguna.
      CONSTRAINT CK_CXC_CU_COORDENADAS CHECK (
        (LATITUD IS NULL AND LONGITUD IS NULL)
        OR (LATITUD BETWEEN -90 AND 90 AND LONGITUD BETWEEN -180 AND 180)),
      -- Al menos la zona o el punto: una fila vacía no sirve.
      CONSTRAINT CK_CXC_CU_ALGUN_DATO CHECK (ID_ZONA IS NOT NULL OR LATITUD IS NOT NULL)
    ) TABLESPACE USERS]');

  ejecutar_si(NOT existe_indice('IX_CXC_CU_ZONA'), q'[
    CREATE INDEX PROYECTOANALISIS.IX_CXC_CU_ZONA
      ON PROYECTOANALISIS.CXC_CLIENTE_UBICACION (ID_ZONA) TABLESPACE USERS]');

  -- ---------------------------------------------------------------------------
  -- 3. CXC_RUTAS.ID_ZONA — territorio de la ruta
  -- ---------------------------------------------------------------------------
  -- NULL en rutas existentes: siguen funcionando como hasta ahora (radio desde la
  -- primera parada) hasta que se les asigne una zona.
  ejecutar_si(NOT existe_columna('CXC_RUTAS', 'ID_ZONA'),
    'ALTER TABLE PROYECTOANALISIS.CXC_RUTAS ADD (ID_ZONA NUMBER)');

  ejecutar_si(NOT existe_constraint('FK_CXC_RUTAS_ZONA'), q'[
    ALTER TABLE PROYECTOANALISIS.CXC_RUTAS ADD CONSTRAINT FK_CXC_RUTAS_ZONA
      FOREIGN KEY (ID_ZONA) REFERENCES PROYECTOANALISIS.CXC_ZONAS_COBRO (ID_ZONA)]');

  ejecutar_si(NOT existe_indice('IX_CXC_RUTAS_ZONA'), q'[
    CREATE INDEX PROYECTOANALISIS.IX_CXC_RUTAS_ZONA
      ON PROYECTOANALISIS.CXC_RUTAS (ID_ZONA) TABLESPACE USERS]');
END;
