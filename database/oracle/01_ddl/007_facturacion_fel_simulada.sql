CREATE TABLE CXC_FACTURA_FEL (
  ID_FACTURA_FEL         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 1 INCREMENT BY 1,
  ID_DOCUMENTO           NUMBER NOT NULL,
  ID_EMPRESA             NUMBER NOT NULL,
  UUID_AUTORIZACION      VARCHAR2(36) NOT NULL,
  SERIE_FEL              VARCHAR2(8) NOT NULL,
  NUMERO_FEL             NUMBER(12) NOT NULL,
  TIPO_DTE               VARCHAR2(6) DEFAULT 'FACT' NOT NULL,
  FECHA_EMISION          DATE NOT NULL,
  FECHA_CERTIFICACION    DATE NOT NULL,
  NIT_EMISOR             VARCHAR2(20) NOT NULL,
  NOMBRE_EMISOR          VARCHAR2(150) NOT NULL,
  NIT_RECEPTOR           VARCHAR2(20) NOT NULL,
  NOMBRE_RECEPTOR        VARCHAR2(150) NOT NULL,
  SUBTOTAL_GRAVADO       NUMBER(12,2) NOT NULL,
  IVA                    NUMBER(12,2) NOT NULL,
  TOTAL                  NUMBER(12,2) NOT NULL,
  ESTADO                 VARCHAR2(12) DEFAULT 'CERTIFICADA' NOT NULL,
  XML_DTE                CLOB,
  ID_EMPLEADO_EMISION    NUMBER NOT NULL,
  FECHA_ANULACION        DATE,
  UUID_ANULACION         VARCHAR2(36),
  MOTIVO_ANULACION       VARCHAR2(250),
  ID_EMPLEADO_ANULACION  NUMBER,
  CONSTRAINT PK_CXC_FACTURA_FEL PRIMARY KEY (ID_FACTURA_FEL),
  CONSTRAINT UQ_CXC_FEL_DOCUMENTO UNIQUE (ID_DOCUMENTO),
  CONSTRAINT UQ_CXC_FEL_UUID UNIQUE (UUID_AUTORIZACION),
  CONSTRAINT UQ_CXC_FEL_SERIE_NUM UNIQUE (SERIE_FEL, NUMERO_FEL),
  CONSTRAINT FK_CXC_FEL_DOCUMENTO FOREIGN KEY (ID_DOCUMENTO) REFERENCES CXC_DOCUMENTOS (ID_DOCUMENTO),
  CONSTRAINT FK_CXC_FEL_EMPRESA FOREIGN KEY (ID_EMPRESA) REFERENCES CXC_EMPRESAS (ID_EMPRESA),
  CONSTRAINT FK_CXC_FEL_EMP_EMISION FOREIGN KEY (ID_EMPLEADO_EMISION) REFERENCES EMPLEADO (ID_EMPLEADO),
  CONSTRAINT FK_CXC_FEL_EMP_ANULA FOREIGN KEY (ID_EMPLEADO_ANULACION) REFERENCES EMPLEADO (ID_EMPLEADO),
  CONSTRAINT CK_CXC_FEL_ESTADO CHECK (ESTADO IN ('CERTIFICADA', 'ANULADA')),
  CONSTRAINT CK_CXC_FEL_TOTAL CHECK (TOTAL > 0 AND SUBTOTAL_GRAVADO >= 0 AND IVA >= 0)
);

CREATE INDEX IX_CXC_FEL_FECHA ON CXC_FACTURA_FEL (FECHA_EMISION);
CREATE INDEX IX_CXC_FEL_NIT_RECEPTOR ON CXC_FACTURA_FEL (NIT_RECEPTOR);

