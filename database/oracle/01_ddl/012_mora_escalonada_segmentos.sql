-- Motivo: la mora deja de ser solo informativa y se le cobra al cliente.
--
--   1. Tramos de mora (CXC_TRAMOS_MORA): el porcentaje sube con los días de
--      mora (contados después de los días de gracia de la condición):
--         1-15 días -> 5 %   16-25 -> 6.5 %   26-40 -> 8 %   41 o más -> 10 %
--   2. Segmentos de cliente A/B/C/D (CXC_SEGMENTOS_CLIENTE): cada segmento
--      resta puntos al porcentaje del tramo como beneficio (nunca baja de 0).
--      El segmento de cada cliente se guarda en CXC_CLIENTE_SEGMENTO, para no
--      alterar la tabla CLIENTE, que comparten otros módulos.
--   3. Notas de débito por mora: el recargo se emite como un documento de cargo
--      del tipo marcado con ES_MORA = 'S'. ID_DOCUMENTO_ORIGEN liga cada nota con
--      la factura vencida que la generó; cuando el atraso sube de tramo se emite
--      otra nota solo por la diferencia.
--
-- Los porcentajes y reducciones de los INSERT son los acordados / propuestos:
-- ajústalos aquí antes de correr el script si la empresa define otros valores.
--
-- 100% aditivo: CREATE TABLE, ALTER TABLE ADD, FK, CHECK, índices e INSERT de
-- catálogos. Ningún DROP, ningún DELETE.
-- =============================================================================

