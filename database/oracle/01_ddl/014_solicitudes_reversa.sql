-- =============================================================================
-- MIGRACIÓN 014 — solicitudes de reversa y anulación con autorización.
-- =============================================================================
-- Motivo: reversar o anular una operación financiera (un pago aplicado al cliente
-- equivocado, una nota de crédito con monto incorrecto, una factura mal emitida...)
-- devuelve o quita deuda. Hasta ahora se hacía al instante. Desde esta migración
-- el usuario la SOLICITA con un motivo y un ADMIN distinto de quien la pidió la
-- aprueba (se ejecuta) o la rechaza (no cambia nada).
--
--   OPERADOR solicita  -> aprueba un ADMIN.
--   ADMIN solicita     -> aprueba OTRO ADMIN.
--   CONSULTA           -> solo consulta.
--
-- Operaciones (TIPO):
--   REVERSA_APLICACION_PAGO      Aplicaciones de pago → Reversar
--   REVERSA_APLICACION_ANTICIPO  Aplicaciones de anticipo → Reversar
--   REVERSA_APLICACION_NC        Aplicaciones de nota de crédito → Reversar
--   ANULACION_PAGO               Pagos → Anular
--   ANULACION_ANTICIPO           Anticipos → Anular
--   ANULACION_NOTA_CREDITO       Notas de crédito → Anular
--   ANULACION_DOCUMENTO          Documentos → Anular
--   ANULACION_FACTURA_FEL        Facturación → Anular
--
-- Estados:
--   PENDIENTE  espera aprobación; los saldos no cambian.
--   APROBADA   un ADMIN la aprobó y la reversa/anulación se ejecutó.
--   RECHAZADA  un ADMIN la rechazó (MOTIVO_RECHAZO).
--   CANCELADA  quien la solicitó la retiró antes de que se resolviera.
--
-- Solicitante y quien resuelve se guardan como USUARIO (SEG_USUARIOS), porque la
-- regla es por usuario y rol, y un ADMIN puede no tener empleado vinculado. El
-- empleado del solicitante (ID_EMPLEADO_SOLICITA) es el que queda registrado como
-- responsable en la reversa/anulación al ejecutarse.
--
-- 100% aditivo: solo CREATE TABLE + FK + CHECK + índices. Ningún DROP ni DELETE.
-- =============================================================================

