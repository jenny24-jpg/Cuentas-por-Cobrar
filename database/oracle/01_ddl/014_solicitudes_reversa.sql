CREATE TABLE "PROYECTOANALISIS"."CXC_SOLICITUDES_REVERSA" (
  "ID_SOLICITUD"          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 1 INCREMENT BY 1,
  "TIPO"                  VARCHAR2(30)  NOT NULL,
  "ID_REGISTRO"           NUMBER        NOT NULL,
  -- Fotografía de lo solicitado para mostrarlo sin recalcular (p. ej. "PAG-2026-000003 → FACT-00000002").
  "REFERENCIA"            VARCHAR2(200),
  "MONTO"                 NUMBER(12,2),
  "MOTIVO"                VARCHAR2(250) NOT NULL,
  "ESTADO"                VARCHAR2(10)  DEFAULT 'PENDIENTE' NOT NULL,
  "ID_USUARIO_SOLICITA"   NUMBER        NOT NULL,
  "ID_EMPLEADO_SOLICITA"  NUMBER        NOT NULL,
  "FECHA_SOLICITUD"       DATE          DEFAULT SYSDATE NOT NULL,
  "ID_USUARIO_RESUELVE"   NUMBER,
  "FECHA_RESOLUCION"      DATE,
  "MOTIVO_RECHAZO"        VARCHAR2(250),
  CONSTRAINT "PK_CXC_SOLICITUDES_REVERSA" PRIMARY KEY ("ID_SOLICITUD"),
  CONSTRAINT "FK_CXC_SR_USUARIO_SOLICITA" FOREIGN KEY ("ID_USUARIO_SOLICITA")
    REFERENCES "PROYECTOANALISIS"."SEG_USUARIOS" ("ID_USUARIO"),
  CONSTRAINT "FK_CXC_SR_EMPLEADO_SOLICITA" FOREIGN KEY ("ID_EMPLEADO_SOLICITA")
    REFERENCES "PROYECTOANALISIS"."EMPLEADO" ("ID_EMPLEADO"),
  CONSTRAINT "FK_CXC_SR_USUARIO_RESUELVE" FOREIGN KEY ("ID_USUARIO_RESUELVE")
    REFERENCES "PROYECTOANALISIS"."SEG_USUARIOS" ("ID_USUARIO"),
  CONSTRAINT "CK_CXC_SR_TIPO" CHECK ("TIPO" IN (
    'REVERSA_APLICACION_PAGO', 'REVERSA_APLICACION_ANTICIPO', 'REVERSA_APLICACION_NC',
    'ANULACION_PAGO', 'ANULACION_ANTICIPO', 'ANULACION_NOTA_CREDITO',
    'ANULACION_DOCUMENTO', 'ANULACION_FACTURA_FEL')),
  CONSTRAINT "CK_CXC_SR_ESTADO" CHECK ("ESTADO" IN ('PENDIENTE', 'APROBADA', 'RECHAZADA', 'CANCELADA')),
  -- Aprobar o rechazar lo hace un usuario distinto de quien la pidió (cancelar la propia sí puede).
  CONSTRAINT "CK_CXC_SR_RESUELVE_DISTINTO" CHECK (
    "ESTADO" IN ('PENDIENTE', 'CANCELADA')
    OR "ID_USUARIO_RESUELVE" <> "ID_USUARIO_SOLICITA"),
  CONSTRAINT "CK_CXC_SR_RECHAZO_CON_MOTIVO" CHECK ("ESTADO" <> 'RECHAZADA' OR "MOTIVO_RECHAZO" IS NOT NULL)
) TABLESPACE "USERS";

-- Una sola solicitud PENDIENTE por operación: no se puede pedir dos veces lo mismo.
CREATE UNIQUE INDEX "PROYECTOANALISIS"."UX_CXC_SR_PENDIENTE"
  ON "PROYECTOANALISIS"."CXC_SOLICITUDES_REVERSA" (
    CASE WHEN "ESTADO" = 'PENDIENTE' THEN "TIPO" END,
    CASE WHEN "ESTADO" = 'PENDIENTE' THEN "ID_REGISTRO" END
  ) TABLESPACE "USERS";

CREATE INDEX "PROYECTOANALISIS"."IX_CXC_SR_ESTADO"
  ON "PROYECTOANALISIS"."CXC_SOLICITUDES_REVERSA" ("ESTADO", "FECHA_SOLICITUD") TABLESPACE "USERS";

CREATE INDEX "PROYECTOANALISIS"."IX_CXC_SR_REGISTRO"
  ON "PROYECTOANALISIS"."CXC_SOLICITUDES_REVERSA" ("TIPO", "ID_REGISTRO") TABLESPACE "USERS";

COMMENT ON TABLE "PROYECTOANALISIS"."CXC_SOLICITUDES_REVERSA" IS
  'Reversas y anulaciones solicitadas; se ejecutan solo cuando un ADMIN distinto del solicitante las aprueba.';

