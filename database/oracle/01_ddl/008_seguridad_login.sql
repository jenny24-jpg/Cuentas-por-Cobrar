-- SEG_USUARIOS        cuentas con contraseña protegida (hash scrypt con sal; nunca
--                     se guarda la contraseña), rol, bloqueo por intentos fallidos
--                     y obligación de cambiar la clave en el primer ingreso.
-- SEG_SESIONES        una fila por inicio de sesión; guarda solo el HASH del token de
--                     renovación (refresh token), con expiración y revocación.
-- SEG_BITACORA_ACCESO traza de seguridad: ingresos, fallos, bloqueos, cierres de
--                     sesión y cambios de clave. Solo se agrega, no se edita.
--
-- 100% aditivo (CREATE TABLE / INDEX). Después de correrlo, crea el primer
-- administrador con:   pnpm --filter @erp/server create-user -- --username admin --nombre "Administrador" --rol ADMIN
-- =============================================================================

