CREATE TABLE SEG_USUARIOS (
  ID_USUARIO          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 1 INCREMENT BY 1,
  ID_EMPLEADO         NUMBER,
  USERNAME            VARCHAR2(50) NOT NULL,
  EMAIL               VARCHAR2(150),
  NOMBRE              VARCHAR2(120) NOT NULL,
  PASSWORD_HASH       VARCHAR2(300) NOT NULL,
  ROL                 VARCHAR2(15) DEFAULT 'OPERADOR' NOT NULL,
  ESTADO              VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL,
  INTENTOS_FALLIDOS   NUMBER(3) DEFAULT 0 NOT NULL,
  BLOQUEADO_HASTA     TIMESTAMP,
  DEBE_CAMBIAR_CLAVE  CHAR(1) DEFAULT 'S' NOT NULL,
  FECHA_CLAVE         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  ULTIMO_LOGIN        TIMESTAMP,
  FECHA_CREACION      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SEG_USUARIOS PRIMARY KEY (ID_USUARIO),
  CONSTRAINT FK_SEG_USU_EMPLEADO FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADO (ID_EMPLEADO),
  CONSTRAINT CK_SEG_USU_ROL CHECK (ROL IN ('ADMIN', 'OPERADOR', 'CONSULTA')),
  CONSTRAINT CK_SEG_USU_ESTADO CHECK (ESTADO IN ('ACTIVO', 'INACTIVO')),
  CONSTRAINT CK_SEG_USU_DEBE_CLAVE CHECK (DEBE_CAMBIAR_CLAVE IN ('S', 'N')),
  CONSTRAINT CK_SEG_USU_INTENTOS CHECK (INTENTOS_FALLIDOS >= 0)
);

-- El usuario es único sin distinguir mayúsculas ("Admin" = "admin").
CREATE UNIQUE INDEX UX_SEG_USU_USERNAME ON SEG_USUARIOS (UPPER(USERNAME));
CREATE INDEX IX_SEG_USU_EMPLEADO ON SEG_USUARIOS (ID_EMPLEADO);

CREATE TABLE SEG_SESIONES (
  ID_SESION           VARCHAR2(36) NOT NULL,
  ID_USUARIO          NUMBER NOT NULL,
  TOKEN_HASH          VARCHAR2(64) NOT NULL,
  FECHA_CREACION      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  FECHA_ULTIMO_USO    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  FECHA_EXPIRA        TIMESTAMP NOT NULL,
  FECHA_REVOCADA      TIMESTAMP,
  MOTIVO_REVOCACION   VARCHAR2(30),
  IP                  VARCHAR2(64),
  USER_AGENT          VARCHAR2(300),
  CONSTRAINT PK_SEG_SESIONES PRIMARY KEY (ID_SESION),
  CONSTRAINT FK_SEG_SES_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES SEG_USUARIOS (ID_USUARIO)
);

CREATE INDEX IX_SEG_SES_USUARIO ON SEG_SESIONES (ID_USUARIO, FECHA_REVOCADA);

CREATE TABLE SEG_BITACORA_ACCESO (
  ID_BITACORA   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 1 INCREMENT BY 1,
  ID_USUARIO    NUMBER,
  USERNAME      VARCHAR2(50),
  EVENTO        VARCHAR2(25) NOT NULL,
  IP            VARCHAR2(64),
  USER_AGENT    VARCHAR2(300),
  DETALLE       VARCHAR2(250),
  FECHA         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SEG_BITACORA_ACCESO PRIMARY KEY (ID_BITACORA)
);

CREATE INDEX IX_SEG_BIT_FECHA ON SEG_BITACORA_ACCESO (FECHA);
CREATE INDEX IX_SEG_BIT_USUARIO ON SEG_BITACORA_ACCESO (ID_USUARIO, FECHA);

