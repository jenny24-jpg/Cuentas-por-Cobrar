-- =============================================================================
-- Motivo: CXC_CONVENIOS_PAGO tenía MONTO_DEUDA como un monto suelto, sin
-- ningún documento asociado. Pagar una cuota de convenio solo bajaba el
-- SALDO de CXC_CONVENIO_CUOTAS, sin tocar jamás CXC_DOCUMENTOS.SALDO: la
-- factura real del cliente seguía mostrando el mismo saldo pendiente aunque
-- el convenio se pagara por completo. Este script crea la tabla de enlace;
-- el server (convenioCuota.repository.ts::registrarPago) ahora distribuye
-- cada pago de cuota entre los documentos reales del convenio reusando el
-- mismo mecanismo de aplicación de pago (bloqueo FOR UPDATE, recibo
-- automático, historial automático) que ya existe para pagos normales.
--
-- 100% aditivo: solo CREATE TABLE + índices + FKs + CHECK. Ningún DROP,
-- ningún DELETE. Seguro de correr aunque ya haya datos.
-- =============================================================================

