CREATE TABLE SEG_BITACORA_ACCION (
  ID_ACCION        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY START WITH 1 INCREMENT BY 1,
  ID_USUARIO       NUMBER NOT NULL,
  USERNAME         VARCHAR2(50) NOT NULL,
  NOMBRE_USUARIO   VARCHAR2(120) NOT NULL,
  ID_EMPLEADO      NUMBER,
  METODO           VARCHAR2(7) NOT NULL,
  RUTA             VARCHAR2(250) NOT NULL,
  ENTIDAD          VARCHAR2(60),
  ID_REGISTRO      NUMBER,
  ACCION           VARCHAR2(40),
  ESTADO_HTTP      NUMBER(3) NOT NULL,
  IP               VARCHAR2(64),
  FECHA            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_SEG_BITACORA_ACCION PRIMARY KEY (ID_ACCION),
  CONSTRAINT FK_SEG_BAC_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES SEG_USUARIOS (ID_USUARIO),
  CONSTRAINT CK_SEG_BAC_METODO CHECK (METODO IN ('POST', 'PUT', 'PATCH', 'DELETE'))
);

CREATE INDEX IX_SEG_BAC_USUARIO ON SEG_BITACORA_ACCION (ID_USUARIO, FECHA);
CREATE INDEX IX_SEG_BAC_REGISTRO ON SEG_BITACORA_ACCION (ENTIDAD, ID_REGISTRO);
CREATE INDEX IX_SEG_BAC_FECHA ON SEG_BITACORA_ACCION (FECHA);

