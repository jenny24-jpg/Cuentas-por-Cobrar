-- =============================================================================
-- MIGRACIÓN 010 — Bitácora de acciones: quién hizo qué en el sistema.
-- =============================================================================
-- SEG_BITACORA_ACCION registra, para cada operación que modifica datos
-- (crear, editar, eliminar, anular, reversar, aprobar...), el usuario de la
-- sesión que la ejecutó. El usuario sale SIEMPRE del token de sesión en el
-- servidor; ningún formulario ni petición puede indicarlo ni cambiarlo.
--
-- Solo se agrega (INSERT). La aplicación no expone ninguna operación para
-- editar ni borrar filas de esta tabla. NOMBRE_USUARIO y USERNAME se guardan
-- como "fotografía" del momento, para que el historial no cambie si después
-- se renombra o se desactiva al usuario.
--
-- 100% aditivo (CREATE TABLE / INDEX), sin PL/SQL ni triggers.
-- =============================================================================

