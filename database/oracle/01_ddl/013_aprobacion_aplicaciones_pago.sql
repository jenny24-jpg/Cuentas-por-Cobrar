-- Permite que los operadores registren solicitudes de aplicación de pago.
-- Solo se reflejan en saldos y recibos cuando un administrador las aprueba.
-- Puede ejecutarse más de una vez, incluso si una ejecución anterior quedó parcial.
DECLARE
  v_count PLS_INTEGER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
   WHERE OWNER = 'PROYECTOANALISIS' AND TABLE_NAME = 'CXC_APLICACION_PAGOS'
     AND COLUMN_NAME = 'ID_EMPLEADO_APROBADOR';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PROYECTOANALISIS.CXC_APLICACION_PAGOS ADD (ID_EMPLEADO_APROBADOR NUMBER)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
   WHERE OWNER = 'PROYECTOANALISIS' AND TABLE_NAME = 'CXC_APLICACION_PAGOS'
     AND COLUMN_NAME = 'FECHA_APROBACION';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PROYECTOANALISIS.CXC_APLICACION_PAGOS ADD (FECHA_APROBACION DATE)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
   WHERE OWNER = 'PROYECTOANALISIS' AND TABLE_NAME = 'CXC_APLICACION_PAGOS'
     AND COLUMN_NAME = 'MOTIVO_RECHAZO';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PROYECTOANALISIS.CXC_APLICACION_PAGOS ADD (MOTIVO_RECHAZO VARCHAR2(250 BYTE))';
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS
   WHERE OWNER = 'PROYECTOANALISIS' AND TABLE_NAME = 'CXC_APLICACION_PAGOS'
     AND CONSTRAINT_NAME = 'FK_CXC_AP_APROBADOR';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PROYECTOANALISIS.CXC_APLICACION_PAGOS ADD CONSTRAINT FK_CXC_AP_APROBADOR FOREIGN KEY (ID_EMPLEADO_APROBADOR) REFERENCES PROYECTOANALISIS.EMPLEADO (ID_EMPLEADO)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_CONSTRAINTS
   WHERE OWNER = 'PROYECTOANALISIS' AND TABLE_NAME = 'CXC_APLICACION_PAGOS'
     AND CONSTRAINT_NAME = 'CK_CXC_AP_ESTADO';
  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PROYECTOANALISIS.CXC_APLICACION_PAGOS DROP CONSTRAINT CK_CXC_AP_ESTADO';
  END IF;
  EXECUTE IMMEDIATE 'ALTER TABLE PROYECTOANALISIS.CXC_APLICACION_PAGOS ADD CONSTRAINT CK_CXC_AP_ESTADO CHECK (ESTADO IN (''PENDIENTE'', ''CONFIRMADA'', ''REVERSADA'', ''RECHAZADA''))';

  SELECT COUNT(*) INTO v_count FROM ALL_INDEXES
   WHERE OWNER = 'PROYECTOANALISIS' AND INDEX_NAME = 'IX_CXC_AP_APROBADOR';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX PROYECTOANALISIS.IX_CXC_AP_APROBADOR ON PROYECTOANALISIS.CXC_APLICACION_PAGOS (ID_EMPLEADO_APROBADOR)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM ALL_INDEXES
   WHERE OWNER = 'PROYECTOANALISIS' AND INDEX_NAME = 'IX_CXC_AP_PENDIENTE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX PROYECTOANALISIS.IX_CXC_AP_PENDIENTE ON PROYECTOANALISIS.CXC_APLICACION_PAGOS (ESTADO, ID_APLICACION)';
  END IF;
END;
